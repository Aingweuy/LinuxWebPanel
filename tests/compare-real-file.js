/**
 * Comparison script for AbyssPartyList table.
 * 
 * Run: node tests/compare-real-file.js
 */

const fs = require('fs');
const path = require('path');
const vm = require('vm');

// ── Load the converter ──────────────────────────────────────────────
const srcPath = path.join(__dirname, '..', 'BTPanel', 'static', 'js', 'csv-bytes-converter.js');
const src = fs.readFileSync(srcPath, 'utf8');
vm.runInThisContext(src, { filename: srcPath }); // defines global csvBytesConverter

// ── Parse 1.5.xml to get column definitions for AbyssPartyList ──────
const xmlPath = 'E:\\TableConverter\\TableConverter\\1.5.xml';
if (!fs.existsSync(xmlPath)) {
    console.error('1.5.xml not found at:', xmlPath);
    process.exit(1);
}
const xmlContent = fs.readFileSync(xmlPath, 'utf8');

// Find AbyssPartyListTable struct
const structRegex = /<PGCVSStruct>([\s\S]*?)<\/PGCVSStruct>/g;
let match;
let foundStruct = null;
while ((match = structRegex.exec(xmlContent)) !== null) {
    const structBody = match[1];
    if (structBody.includes('<TableName>AbyssPartyList</TableName>') || structBody.includes('<TableName>AbyssPartyList|')) {
        foundStruct = structBody;
        break;
    }
}
if (!foundStruct) {
    console.error('AbyssPartyListTable struct not found in 1.5.xml');
    process.exit(1);
}

// Extract fields
const fieldRegex = /<PGCVSField>([\s\S]*?)<\/PGCVSField>/g;
let fieldMatch;
const xmlFields = [];
while ((fieldMatch = fieldRegex.exec(foundStruct)) !== null) {
    const fieldBody = fieldMatch[1];
    const name = fieldBody.match(/<Name>(.*?)<\/Name>/)[1];
    const type = fieldBody.match(/<Type>(.*?)<\/Type>/)[1];
    const clientTypeMatch = fieldBody.match(/<ClientType>(.*?)<\/ClientType>/);
    const clientType = clientTypeMatch ? clientTypeMatch[1] : type;
    const colNameInExcel = fieldBody.match(/<ColNameInExcel>(.*?)<\/ColNameInExcel>/)[1];
    const serverOnlyMatch = fieldBody.match(/<ServerOnly>(.*?)<\/ServerOnly>/);
    const serverOnly = serverOnlyMatch ? serverOnlyMatch[1] === 'true' : false;

    if (!serverOnly) {
        xmlFields.push({ name, type, clientType: clientType.replace(/&lt;/g, '<').replace(/&gt;/g, '>'), colNameInExcel });
    }
}

console.log('XML Client-Side Fields:', xmlFields.map(f => `${f.colNameInExcel}(${f.clientType})`));

// ── Read AbyssPartyList.txt ─────────────────────────────────────────
const txtPath = 'E:\\TableConverter\\TableConverter\\table\\AbyssPartyList.txt';
if (!fs.existsSync(txtPath)) {
    console.error('Source file not found at:', txtPath);
    process.exit(1);
}

// AbyssPartyList.txt is UTF-16LE encoded. Read it.
let txtContent = fs.readFileSync(txtPath, 'utf16le');
if (txtContent.charCodeAt(0) === 0xFEFF) {
    txtContent = txtContent.substring(1);
}

// Split into lines
const lines = txtContent.split(/\r?\n/);
console.log('Total lines in txt:', lines.length);

const tableData = [];
lines.forEach(line => {
    if (line.trim() === '') return;
    tableData.push(line.split('\t'));
});

console.log('Rows parsed:', tableData.length);
console.log('Header columns:', tableData[0]);

// Build columnDefs matching the XML fields and header columns
const headerCols = tableData[0];
const columnDefs = [];

// For each column in the XML fields (since output is written in XML Field order),
// we map it to the corresponding column index in the TXT file.
// Note: If an XML field maps to a column not in the TXT, FindFieldIndex returns -1.
// We must build columnDefs in the order of the XML fields!
// Wait! Let's check: does the generated bytes have the columns in the XML Fields order?
// Yes! CVSData.cs writes each column in the order of this.colMap (which is in the order of cvsStruct.Fields!).
// So when we call convertTableToBytes, the tableData columns must be mapped to the XML Fields.
// Let's reorganize tableData so that the columns of tableData match the XML Fields order!
const reorderedTableData = [];
for (let r = 0; r < tableData.length; r++) {
    reorderedTableData.push([]);
}

for (let f = 0; f < xmlFields.length; f++) {
    const xmlField = xmlFields[f];
    const colName = xmlField.colNameInExcel;
    
    // Find index in TXT header
    const txtColIdx = headerCols.findIndex(name => name.trim() === colName);
    if (txtColIdx === -1) {
        console.warn(`WARNING: XML field "${colName}" not found in TXT file columns!`);
        // Fill with empty string for all rows
        for (let r = 0; r < tableData.length; r++) {
            reorderedTableData[r].push(r === 0 ? colName : '');
        }
    } else {
        // Copy column
        for (let r = 0; r < tableData.length; r++) {
            reorderedTableData[r].push(tableData[r][txtColIdx]);
        }
    }

    // Determine types for columnDefs
    const clientType = xmlField.clientType;
    let fieldType = csvBytesConverter.EFieldType.EValue;
    let dataType = csvBytesConverter.EDataType.STRING;
    let count = 2;
    let post = 'S';
    let baseType = clientType;

    // Check array (vector<...>)
    if (clientType.startsWith('vector<')) {
        fieldType = csvBytesConverter.EFieldType.EArray;
        if (clientType.includes('Sequence<')) {
            fieldType = csvBytesConverter.EFieldType.ESeqList;
            const inner = clientType.match(/Sequence<(.*?),\s*(\d+)>/);
            baseType = inner[1];
            count = parseInt(inner[2], 10);
        } else {
            baseType = clientType.substring(7, clientType.length - 1);
        }
    }
    // Check sequence (Sequence<type, count>)
    else if (clientType.startsWith('Sequence<')) {
        fieldType = csvBytesConverter.EFieldType.ESeq;
        const inner = clientType.match(/Sequence<(.*?),\s*(\d+)>/);
        baseType = inner[1];
        count = parseInt(inner[2], 10);
    }

    dataType = csvBytesConverter.parseTypeName(baseType);
    post = csvBytesConverter.getPostSuffix(dataType);

    columnDefs.push({ fieldType, dataType, count, post });
}

console.log('\nReordered Header columns:', reorderedTableData[0]);
columnDefs.forEach((def, idx) => {
    console.log(`Column ${idx} [${reorderedTableData[0][idx]}]: fieldType=${def.fieldType} dataType=${def.dataType} count=${def.count} post=${def.post}`);
});

// ── Generate .bytes binary ─────────────────────────────────────────
console.log('\nGenerating .bytes using JS converter...');
const generatedBytes = csvBytesConverter.convertTableToBytes(reorderedTableData, {
    skipSecondRow: true, // line 2 is type-hint comment row
    columnDefs: columnDefs
});

console.log('Generated output size:', generatedBytes.length, 'bytes');

// ── Read expected output ───────────────────────────────────────────
const expectedPath = 'E:\\TableConverter\\TableConverter\\table\\Output\\AbyssPartyList.bytes';
if (!fs.existsSync(expectedPath)) {
    console.error('Expected bytes file not found at:', expectedPath);
    process.exit(1);
}
const expectedBytes = fs.readFileSync(expectedPath);
console.log('Expected output size:', expectedBytes.length, 'bytes');

// Save our generated bytes to a temporary file
const tempPath = path.join(__dirname, 'temp_AbyssPartyList.bytes');
fs.writeFileSync(tempPath, generatedBytes);
console.log('Saved generated bytes to:', tempPath);

// ── Compare byte-by-byte ───────────────────────────────────────────
let diffs = 0;
const limit = 20;
const diffIndexes = [];

const minLen = Math.min(generatedBytes.length, expectedBytes.length);
for (let i = 0; i < minLen; i++) {
    if (generatedBytes[i] !== expectedBytes[i]) {
        diffs++;
        if (diffIndexes.length < limit) {
            diffIndexes.push(i);
        }
    }
}

const lenDiff = Math.abs(generatedBytes.length - expectedBytes.length);
if (lenDiff > 0) {
    console.log(`\nSize difference: ${lenDiff} bytes!`);
}

if (diffs === 0 && lenDiff === 0) {
    console.log('\nSUCCESS! Generated bytes are 100% IDENTICAL to expected bytes!');
    fs.unlinkSync(tempPath);
    process.exit(0);
} else {
    console.log(`\nFAILURE: Found ${diffs} byte differences!`);
    console.log(`First ${diffIndexes.length} differences at offsets:`);
    diffIndexes.forEach(idx => {
        console.log(`  Offset 0x${idx.toString(16).toUpperCase()} (${idx}): Actual = 0x${generatedBytes[idx].toString(16).toUpperCase().padStart(2, '0')} (${generatedBytes[idx]}), Expected = 0x${expectedBytes[idx].toString(16).toUpperCase().padStart(2, '0')} (${expectedBytes[idx]})`);
    });
    process.exit(1);
}
